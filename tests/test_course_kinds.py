class Sentences(Shared):
    """Put the chunks in order: judged by code, shown shuffled, checked blind."""
    def setUp(self):
        super().setUp()
        home = Path(self.tmp.name) / 'lessons' / 'my-order'
        home.mkdir(parents=True)
        stored = [{k: v for k, v in item.items() if v not in ('', [])} for item in (FIRST, SECOND)]
        files = {'course.json': {'version': 3, 'id': 'my-order', 'title': '演示', 'language': 'de',
                                 'sections': [{'id': 'writing', 'title': '写作', 'venue': 'chat', 'lessons': ['writing-order']}]},
                 'kinds.json': {'sentence': {'format': 'reading', 'spec': '出两道连词成句。', 'example': ORDER,
                                             'checks': {'groups': 1, 'items': 2, 'answer': 'order', 'chunks': [3, 6]}}},
                 'writing-order.json': {'id': 'writing-order', 'title': '连词成句', 'goal': 'g', 'skill': 'writing', 'exam': '演示', 'sources': [],
                                        'points': [{'id': 'order', 'label': '词序'}],
                                        'cards': [{'id': 'try', 'type': 'check', 'title': '练习', 'points': ['order'],
                                                   'groups': [{'label': 'Make an appropriate sentence.', 'items': stored[:1]}]},
                                                  {'id': 'timed', 'type': 'quiz', 'title': '限时练习', 'minutes': 3, 'pass': 0.5, 'points': ['order'],
                                                   'sets': [{'id': 'set-a', 'groups': [{'label': 'Make an appropriate sentence.', 'items': stored}]}],
                                                   'more': {'kind': 'sentence', 'topics': ['一', '二', '三', '四', '五']}}]}}
        for name, value in files.items():
            (home / name).write_text(json.dumps(value, ensure_ascii=False), 'utf-8')
        self.stored = stored
        guard = patch.object(lessons, 'CUSTOM', home.parent)
        guard.start()
        self.addCleanup(lessons.reload)
        self.addCleanup(guard.stop)
        lessons.reload()
        with closing(db.get_conn()) as conn, conn:
            course.save_language_settings(conn, 'de', course.Teaching(mode='ambient', preset='my-order'))

    def practice(self):
        return self.post('start', {'language': 'de', 'lesson_id': 'writing-order', 'practice': True}, 201)['lesson']

    def test_the_chunks_are_shown_shuffled_and_judged_by_code(self):
        new = self.post('start', {'language': 'de', 'lesson_id': 'writing-order'}, 201)['lesson']
        self.assertEqual(new['cards'][0]['groups'][0]['items'], self.stored[:1])       # a practice card carries its answers, as always
        self.post('stop')
        lesson = self.practice()
        first, second = lesson['set']['groups'][0]['items']
        self.assertEqual(set(first), {'stem', 'lead', 'tail', 'pool', 'slots', 'point'})
        self.assertEqual(set(second), {'stem', 'pool', 'slots', 'point'})
        self.assertEqual((sorted(first['pool']), first['slots']), (sorted(FIRST['chunks'] + FIRST['extra']), 5))
        self.assertEqual(self.view()['set'], lesson['set'])                                # the same order every time it is looked at
        wrong = ["Let's", 'meet', 'the library', 'in front of']
        self.post('quiz', {'answers': [[FIRST['chunks']]], 'seconds': 5}, 422)             # one answer per question
        done = self.post('quiz', {'answers': [[FIRST['chunks'], wrong]], 'seconds': 50})['lesson']
        self.assertEqual((done['result']['groups'], done['result']['score'], done['result']['answers']), ([[True, False]], 1, [[FIRST['chunks'], wrong]]))
        self.assertEqual(done['set']['groups'][0]['items'], self.stored)                   # the answers are back, the pool is gone

    def test_a_new_set_is_checked_by_ordering_it_blind(self):
        self.practice()
        self.post('quiz', {'answers': [[FIRST['chunks'], SECOND['chunks']]], 'seconds': 50})
        long = copy.deepcopy(ORDER)
        long['groups'][0]['items'][1]['chunks'] = ['a', 'b', 'c', 'd', 'e', 'f', 'g']
        asked = []
        def order(sent):
            asked.append(sent)
            return {'answers': [FIRST['chunks'], SECOND['chunks'][::-1] if len(asked) == 1 else SECOND['chunks']]}
        model = self.use(Model([long, ORDER], order=order))
        rng = Mock(wraps=clock.rng)
        with patch.object(clock, 'rng', rng):
            self.assertEqual(self.practice()['set']['id'], 'g1')
        first, second, third = model.made()
        self.assertTrue(first.startswith(SPECS['head'] + '出两道连词成句。' + SPECS['items_order'] + '\n'))
        self.assertEqual(json.loads(first.rsplit('\n', 1)[1])['properties']['groups']['items']['properties']['items']['items'], SPECS['item']['order'])
        self.assertTrue(second.endswith(retry('count', key='chunks', got=7, low=3, high=6)))
        self.assertTrue(third.endswith(retry('blind', n=2)))
        questions = asked[0][0]['questions']
        self.assertEqual([set(q) for q in questions], [{'stem', 'lead', 'tail', 'pool'}] * 2)
        self.assertEqual(sorted(questions[0]['pool']), sorted(FIRST['chunks'] + FIRST['extra']))
        self.assertEqual(json.loads(self.generated()[0]['payload_json'])['groups'][0]['items'], self.stored)


