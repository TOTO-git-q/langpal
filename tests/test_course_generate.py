def plain(fill):
    return re.sub(r'\{(\w+)\}', r'\1', fill)


class Gaps(unittest.TestCase):
    def test_the_official_rule_reproduces_the_authored_paragraphs(self):
        lesson = authored('reading-complete-words')
        groups = [g for card in lesson['cards'] for g in card.get('groups', []) + [g for s in card.get('sets', []) for g in s['groups']]
                  if card['id'] in ('check-passage', 'timed')]
        self.assertEqual(len(groups), 9)
        for group in groups:                                  # includes a paragraph where a one-letter word is skipped
            self.assertEqual(course.generate.gaps(plain(group['fill'])), (group['fill'], group['tags']))

    def test_paragraphs_that_cannot_be_cut_cleanly_are_refused(self):
        good = plain(authored('reading-complete-words')['cards'][-1]['sets'][0]['groups'][0]['fill'])
        first, rest = good.split('. ', 1)
        for bad in (first + '. Too short to cut ten words from it.',
                    first + '. The well-known builders ' + rest,                  # a hyphen lands on a cut word
                    first + ". They didn't know why, but " + rest,                # an apostrophe lands on a cut word
                    first + '. The Roman engineers ' + rest[5:]):                  # a capitalised word inside a sentence is cut
            with self.assertRaises(ValueError):
                course.generate.gaps(bad)


class Model:
    """Fake utility model: routes by the prompt it is given. Counts calls and keeps the prompts."""
    def __init__(self, make, blind=None, fill=None, mark=None, blank=None, order=None):
        self.make, self.blind, self.fill, self.mark, self.blank, self.order, self.prompts, self.delay = make, blind, fill, mark, blank, order, [], 0

    async def generate_json(self, prompt, schema):
        self.prompts.append(prompt)
        if prompt.startswith(SPECS['blind_order']):
            return self.order(json.loads(prompt[len(SPECS['blind_order']):].split('\n', 1)[0]))
        if prompt.startswith(SPECS['blind_blank']):
            return self.blank(json.loads(prompt[len(SPECS['blind_blank']):].split('\n', 1)[0]))
        if prompt.startswith(SPECS['blind']):
            return self.blind(json.loads(prompt[len(SPECS['blind']):].split('\n', 1)[0]))
        if prompt.startswith(SPECS['fill']):
            return self.fill(prompt)
        if prompt.startswith(SPECS['head']):
            await asyncio.sleep(self.delay)
            answer = self.make.pop(0) if len(self.make) > 1 else self.make[0]
            if isinstance(answer, Exception):
                raise answer
            return copy.deepcopy(answer)
        return copy.deepcopy(self.mark)

    def made(self):
        return [p for p in self.prompts if p.startswith(SPECS['head'])]


class More(Base):
    def use(self, model):
        guard = patch('app.providers.registry.get_utility_provider', return_value=model)
        guard.start()
        self.addCleanup(guard.stop)
        return model

    def generated(self):
        with closing(db.get_conn()) as conn:
            return [dict(row) for row in conn.execute('SELECT * FROM course_generated ORDER BY id')]

    def practice(self, name=LESSON, status=201):
        return self.post('start', {'language': 'en', 'lesson_id': name, 'practice': True}, status)

    def write_all_authored(self, model):
        for task in ('workshop', 'panel', 'library'):
            lesson = self.practice()['lesson']
            self.assertEqual((len(lesson['cards']), lesson['task']['id']), (1, task))
            self.assertEqual(self.post('submit', {'text': ESSAY, 'seconds': 300})['lesson']['ended'], True)
        self.assertEqual(model.made(), [])                                # nothing was written while authored tasks remained

    def test_practice_goes_straight_to_the_last_card_without_her_opening_line(self):
        self.use(Model([EMAIL], mark=sheet()))
        lesson = self.practice()['lesson']
        self.assertEqual([c['type'] for c in lesson['cards']], ['write'])
        self.assertEqual(self.said, [])
        self.post('submit', {'text': ESSAY, 'seconds': 300})
        self.assertEqual(self.topped, [('en', LESSON)])                    # every finished lesson asks for a top-up

    def test_when_the_authored_tasks_are_used_up_the_model_writes_new_ones(self):
        model = self.use(Model([EMAIL, {**EMAIL, 'purpose': '第二道'}], mark=sheet()))
        self.write_all_authored(model)
        first = self.practice()['lesson']
        card = authored(LESSON)['cards'][-1]
        self.assertEqual({k: first['task'][k] for k in ('id', 'purpose', 'setting', 'lead', 'bullets', 'to', 'subject')}, {'id': 'g1', **{k: EMAIL[k] for k in EMAIL if k != 'must'}})
        self.assertFalse({'must', 'model'} & set(first['task']))
        prompt = model.made()[0]
        self.assertTrue(prompt.startswith(SPECS['head'] + KINDS['email']['spec'] + '\n'))
        payload = json.loads(prompt[len(SPECS['head'] + KINDS['email']['spec']) + 1:].split('\n', 1)[0])
        self.assertEqual(payload['topic'], card['more']['topics'][0])
        self.assertEqual(payload['example'], KINDS['email']['example'])
        self.assertEqual(payload['avoid'], [task['purpose'] for task in card['tasks']])
        self.assertEqual([p['id'] for p in payload['points']], ['coverage', 'register', 'accuracy'])
        done = self.post('submit', {'text': ESSAY, 'seconds': 300})['lesson']
        self.assertEqual((done['task']['must'], 'model' in done['task']), (EMAIL['must'], False))
        self.assertEqual({r['context'] for r in self.rows()[-3:]}, {'g1'})
        second = self.practice()['lesson']
        self.assertEqual((second['task']['id'], second['task']['purpose']), ('g2', '第二道'))
        topics = [json.loads(p[len(SPECS['head'] + KINDS['email']['spec']) + 1:].split('\n', 1)[0])['topic'] for p in model.made()]
        self.assertEqual(topics, card['more']['topics'][:2])
        self.assertEqual([(row['item_id'], row['topic']) for row in self.generated()], list(zip(['g1', 'g2'], topics)))

