    def test_a_question_set_is_shuffled_and_must_survive_a_blind_re_answer(self):
        source = authored('reading-daily-life')['cards'][-1]
        made = copy.deepcopy({'groups': source['sets'][1]['groups']})
        made['groups'][0]['items'][0]['why'] = 'B 才对，A 说反了。'              # letters are rewritten with the shuffle
        right = {item['stem']: item['options'][item['answer']] for group in made['groups'] for item in group['items']}
        tries = []
        def blind(sent):
            tries.append(sent)
            answers = [q['options'].index(right[q['stem']]) for part in sent for q in part['questions']]
            if len(tries) == 1:
                answers[2] = (answers[2] + 1) % 4                                # the first set fails the check
            return {'answers': answers}
        model = self.use(Model([made], blind=blind))
        for _ in source['sets']:                                                 # use up both authored sets
            lesson = self.practice('reading-daily-life')['lesson']
            authored_set = next(s for s in source['sets'] if s['id'] == lesson['set']['id'])
            self.post('quiz', {'answers': [key(g) for g in authored_set['groups']], 'seconds': 100})
        with patch.object(clock, 'rng', random.Random(7)):
            lesson = self.practice('reading-daily-life')['lesson']
        self.assertEqual((lesson['set']['id'], len(model.made()), len(tries)), ('g1', 2, 2))
        self.assertEqual(set(tries[0][0]), {'material', 'questions'})
        self.assertEqual(set(tries[0][0]['questions'][0]), {'stem', 'options'})   # no answers, no explanations
        stored = json.loads(self.generated()[0]['payload_json'])
        items = [item for group in stored['groups'] for item in group['items']]
        original = [item for group in made['groups'] for item in group['items']]
        self.assertEqual([item['options'][item['answer']] for item in items], [right[item['stem']] for item in items])
        self.assertEqual([sorted(item['options']) for item in items], [sorted(item['options']) for item in original])
        self.assertNotEqual([item['options'] for item in items], [item['options'] for item in original])
        letter = lambda item, text: 'ABCD'[item['options'].index(text)]
        self.assertEqual(items[0]['why'], f"{letter(items[0], original[0]['options'][1])} 才对，{letter(items[0], original[0]['options'][0])} 说反了。")
        done = self.post('quiz', {'answers': [key(g) for g in stored['groups']], 'seconds': 100})['lesson']
        self.assertEqual((done['result']['passed'], done['set']), (True, stored))

    def test_word_completion_paragraphs_are_refused_only_when_another_word_fits(self):
        lesson = authored('reading-complete-words')
        two = [plain(g['fill']) for g in lesson['cards'][-1]['sets'][0]['groups']]
        keys = [re.findall(r'[A-Za-z]*\{[a-z]+\}', g['fill']) for g in lesson['cards'][-1]['sets'][0]['groups']]
        words = [[plain(w) for w in group] for group in keys]
        def run(change):
            calls = []
            def fill(prompt):
                calls.append(prompt)
                answer = list(words[0 if two[0].split('. ')[0] in prompt else 1])
                change(len(calls), answer)
                return {'words': answer}
            self.use(Model([{'paragraphs': two}], fill=fill))
            made = asyncio.run(course.generate.make('en', 'reading-complete-words'))
            return made, calls
        made, calls = run(lambda n, answer: None)
        self.assertEqual([g['fill'] for g in made['groups']], [g['fill'] for g in lesson['cards'][-1]['sets'][0]['groups']])
        self.assertEqual((made['id'], len(calls)), ('g1', 2))
        self.assertIn('_', calls[0])
        self.assertNotIn('{', calls[0][len(SPECS['fill']):].split('\n', 1)[0])
        made, _ = run(lambda n, answer: answer.__setitem__(0, answer[0] + 's'))   # the model miscounted letters: not an ambiguity
        self.assertEqual(made['id'], 'g2')
        def swap(n, answer):
            answer[1] = answer[1][:-1] + ('x' if answer[1][-1] != 'x' else 'y')   # a different word of the same length fits
        made, _ = run(swap)
        self.assertIsNone(made)
        self.assertEqual(len(self.generated()), 2)

    def test_a_finished_lesson_tops_up_only_when_nothing_unused_is_left(self):
        model = self.use(Model([EMAIL], mark=sheet()))
        asyncio.run(course.generate.refill('en', LESSON))                  # three authored tasks are still unused
        self.assertEqual((model.made(), self.generated()), ([], []))
        self.write_all_authored(model)
        asyncio.run(course.generate.refill('en', LESSON))
        asyncio.run(course.generate.refill('en', LESSON))                  # one spare is enough
        self.assertEqual((len(model.made()), [row['item_id'] for row in self.generated()]), (1, ['g1']))
        self.assertEqual(self.practice()['lesson']['task']['id'], 'g1')    # the spare is used without another call
        self.assertEqual(len(model.made()), 1)

    def test_one_more_waits_for_the_spare_that_is_already_being_written(self):
        model = self.use(Model([EMAIL], mark=sheet()))
        self.write_all_authored(model)
        model.delay = 0.6                                                  # the background top-up is still waiting for the model
        worker = threading.Thread(target=lambda: asyncio.run(course.generate.refill('en', LESSON)))
        worker.start()
        time.sleep(0.2)
        self.assertEqual(self.practice()['lesson']['task']['id'], 'g1')    # not a 503: it waits and takes that one
        worker.join()
        self.assertEqual((len(model.made()), len(self.generated())), (1, 1))


