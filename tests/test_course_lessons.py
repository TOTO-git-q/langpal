    def test_passing_with_one_slip_still_counts_and_failing_marks_only_the_points_that_slipped(self):
        sets = {s['id']: s for s in authored('reading-daily-life')['cards'][-1]['sets']}
        def run(pick):
            source = sets[self.to_quiz('reading-daily-life')['set']['id']]
            points = [item['point'] for group in source['groups'] for item in group['items']]
            wrong = pick(points)
            answers, n = [], 0
            for group in source['groups']:
                row = []
                for right in key(group):
                    row.append((right + 1) % 4 if n in wrong else right)
                    n += 1
                answers.append(row)
            before = len(self.rows())
            result = self.post('quiz', {'answers': answers, 'seconds': 100})['lesson']['result']
            return result, len(wrong), {r['point_id']: r['result'] for r in self.rows()[before:]}
        result, _, rows = run(lambda points: {points.index('detail')})
        self.assertEqual((result['score'], result['passed'], rows), (7, True, dict.fromkeys(('purpose', 'detail', 'informal'), 'success')))
        self.now = START + timedelta(days=1)
        result, missed, rows = run(lambda points: {i for i, point in enumerate(points) if point == 'detail'})
        self.assertEqual((result['score'], result['passed'], rows), (8 - missed, False, {'detail': 'miss'}))

