class Shipped(unittest.TestCase):
    def test_every_shipped_course_and_lesson_file_loads(self):
        for path in sorted(SHIPPED.glob('*/course.json')):
            listed = course.lessons.Course.model_validate_json(path.read_text('utf-8'))
            names = {name for part in listed.sections for name in part.lessons}
            for part in listed.sections:
                for group in part.parts or []:
                    self.assertLessEqual(set(group.lessons), set(part.lessons), path)
                    if group.practice:
                        if group.practice.lesson:                                  # a speaking practice opens the coach and holds no questions
                            self.assertTrue((path.parent / (group.practice.lesson + '.json')).is_file(), group.practice.lesson)
                        self.assertLessEqual(set(group.practice.points.values()), names, group.title)
            for file in sorted(path.parent.glob('*.json')):
                if file.name not in ('course.json', 'kinds.json'):
                    with self.subTest(file=file.name):
                        self.assertEqual(course.lessons.Lesson.model_validate_json(file.read_text('utf-8')).id, file.stem)
                        self.assertIn(file.stem, names)


class Parts(Base):
    """A course with parts: catalog lessons are read as one page, the holder of a practice is never offered as a lesson."""
    def setUp(self):
        super().setUp()
        with closing(db.get_conn()) as conn, conn:
            course.save_language_settings(conn, 'en', course.Teaching(mode='ambient', preset=PARTS))
        self.fact = json.loads((LESSONS / PARTS / 'reading-passage-fact.json').read_text('utf-8'))

    def test_the_holder_of_a_practice_is_not_the_next_lesson(self):
        self.assertEqual(self.progress()['next'], {'unit_id': 'reading-passage-fact', 'title': self.fact['title']})
        self.assertEqual(self.start()['lesson_id'], 'reading-passage-fact')

    def test_a_catalog_lesson_is_one_page_and_she_does_not_open_it(self):
        lesson = self.start(lesson_id='reading-passage-fact')
        self.assertEqual((lesson['venue'], lesson['practice']), ('page', None))
        self.assertEqual([card['id'] for card in lesson['cards']], [card['id'] for card in self.fact['cards']])
        self.assertEqual(lesson['set']['id'], 'set-a')
        self.assertEqual(self.said, [])

    def test_a_lesson_that_is_already_known_is_still_read_whole(self):
        self.start(lesson_id='reading-passage-fact')
        source = self.fact['cards'][-1]['sets'][0]
        done = self.post('quiz', {'answers': [key(group) for group in source['groups']], 'seconds': 100})['lesson']
        self.assertTrue(done['result']['passed'])
        unit = next(u for u in self.progress()['units'] if u['id'] == 'reading-passage-fact')
        self.assertEqual(unit['status'], 'known')                                 # "mastery": "once"
        again = self.start(lesson_id='reading-passage-fact')
        self.assertEqual((again['venue'], len(again['cards'])), ('page', len(self.fact['cards'])))

    def test_a_practice_carries_its_brief_and_the_lessons_that_teach_it(self):
        lesson = self.start(lesson_id='reading-academic', practice=True)
        self.assertEqual((lesson['venue'], len(lesson['cards'])), ('page', 1))
        self.assertEqual(lesson['practice'], {
            'brief': ['先读题干，再回原文定位。', '正确选项是原文的同义改写。'],
            'lessons': [{'id': 'reading-passage-fact', 'title': self.fact['title'], 'ready': True},
                        {'id': 'reading-passage-next', 'title': '下一课', 'ready': False}]})

    def test_a_writing_practice_points_back_to_the_written_lesson_of_the_first_missed_point(self):
        practice = self.start(lesson_id='writing-email', practice=True)
        self.assertEqual((practice['venue'], practice['review']), ('chat', None))
        answer = sheet(score=3)
        answer['points'][0]['met'] = False       # coverage: taught by reading-passage-next, which is not written yet
        answer['points'][2]['met'] = False       # accuracy: taught by reading-passage-fact
        self.model(answer)
        done = self.post('submit', {'text': ESSAY, 'seconds': 300})['lesson']
        self.assertEqual(done['sheet']['next'], 'reading-passage-fact')
        self.assertEqual(done['review'], {'id': 'reading-passage-fact', 'title': self.fact['title']})
        closing_line = (section('### 7.5')[1].replace('{score}', '3').replace('{reason}', '大体有效，容易看懂。')
                        .replace('{fix}', 'I very like taking photos → I really like taking photos'))
        self.assertEqual(self.said, [closing_line])     # written in the chat: she answers there
        self.model(sheet())
        self.start(lesson_id='writing-email', practice=True)
        self.assertEqual(self.post('submit', {'text': ESSAY, 'seconds': 300})['lesson']['review'], None)   # all met

    def test_a_speaking_practice_opens_the_coach_and_holds_no_questions(self):
        def listed(practice):
            return course.lessons.Course.model_validate({'version': 3, 'id': 'x', 'title': 'x', 'language': 'en', 'sections': [
                {'id': 'speaking', 'title': '口语', 'venue': 'speaking', 'lessons': ['speaking-a'],
                 'parts': [{'title': '跟读', 'lessons': ['speaking-a'], 'practice': practice}]}]})
        base = {'title': '跟读', 'brief': ['先听完整句。'], 'points': {'chunks': 'speaking-a'}}
        self.assertEqual(course.lessons.holders(listed({**base, 'open': 'shadowing'})), set())
        self.assertEqual(course.lessons.holders(listed({**base, 'lesson': 'speaking-a'})), {'speaking-a'})
        for bad in ({}, {'open': 'shadowing', 'lesson': 'speaking-a'}, {'open': 'elsewhere'}):
            with self.assertRaises(ValueError):
                listed({**base, **bad})


