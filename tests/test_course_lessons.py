class Audio(Base):
    def setUp(self):
        super().setUp()
        self.made = []
        def fake(language, lines):
            self.made.append((language, lines))
            return b'RIFF-fake-wav-' + str(len(self.made)).encode()
        for name, value in (('synthesize', fake), ('AUDIO_DIR', Path(self.tmp.name) / 'lesson_audio')):
            guard = patch.object(course.lesson, name, value)
            guard.start()
            self.addCleanup(guard.stop)

    def audio(self, status=200, **params):
        response = self.client.get('/api/teaching/lesson/audio', params=params)
        self.assertEqual(response.status_code, status, response.text)
        return response

    def walk(self, name, kind):
        lesson = self.start(lesson_id=name)
        return lesson

    def test_a_recording_is_made_once_and_then_read_from_disk(self):
        self.audio(404, card='check', group=0)                                   # no lesson yet
        self.walk('listening-conversation', 'check')
        source = authored('listening-conversation')
        group = next(c for c in source['cards'] if c['id'] == 'check')['groups'][1]
        first = self.audio(card='check', group=1)
        self.assertEqual((first.headers['content-type'], first.content), ('audio/wav', b'RIFF-fake-wav-1'))
        expected = [{'who': 'A', 'text': group['audio']['intro']}, *group['audio']['lines']]
        self.assertEqual(self.made, [('en', expected)])
        self.assertEqual(self.audio(card='check', group=1).content, first.content)
        self.assertEqual(len(self.made), 1)                                      # the second request did not synthesize
        self.audio(card='timed', group=0)
        self.audio(404, card='check', group=9)
        self.assertEqual(self.client.get('/api/teaching/lesson/audio', params={'card': 'check', 'group': 1},
                                         headers={'origin': 'https://evil.example'}).status_code, 403)

    def test_a_line_without_an_intro_is_sent_as_it_is_and_the_quiz_uses_its_own_set(self):
        lesson = self.walk('listening-response', 'quiz')
        self.assertNotIn('lines', lesson['set']['groups'][0]['audio'])           # the script is hidden until the quiz is handed in
        self.audio(card='timed', group=2)
        source = authored('listening-response')['cards'][-1]['sets'][0]['groups'][2]
        self.assertEqual(self.made[-1], ('en', source['audio']['lines']))

    def test_no_recording_where_there_is_nothing_to_hear_and_failures_are_503(self):
        self.walk('reading-daily-life', 'check')
        self.audio(404, card='worked', group=0)
        self.walk('listening-talk', 'check')
        with patch.object(course.lesson, 'synthesize', side_effect=RuntimeError('no voice')):
            self.audio(503, card='worked', group=0)
        self.assertEqual(self.audio(card='worked', group=0).content[:4], b'RIFF')  # a failure is not cached


