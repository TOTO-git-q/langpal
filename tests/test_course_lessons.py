def section(title):
    """Untagged fenced blocks of one '### ' section of the spec."""
    start = SPEC.index(title)
    after = start + len(title)
    following = re.search(r'^#{2,3} ', SPEC[after:], re.M)
    body = SPEC[start:after + following.start()] if following else SPEC[start:]
    return [block.strip('\n') for tag, block in re.findall(r'```(\w*)\n(.*?)```', body, re.S) if not tag]


class Model:
    """Fake utility provider: hands out queued answers and records the prompts."""
    def __init__(self, *answers):
        self.answers, self.prompts = list(answers), []

    async def generate_json(self, prompt, schema):
        self.prompts.append(prompt)
        answer = self.answers.pop(0) if len(self.answers) > 1 else self.answers[0]
        if isinstance(answer, Exception):
            raise answer
        return copy.deepcopy(answer)


class Base(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.now = START
        for target, name, value in ((db, 'DB_PATH', Path(self.tmp.name) / 'course.db'), (clock, 'now', lambda: self.now)):
            guard = patch.object(target, name, value)
            guard.start()
            self.addCleanup(guard.stop)
        self.addCleanup(course.lessons.reload)              # runs after the directory is put back
        guard = patch.object(course.lessons, 'DIRECTORY', LESSONS)
        guard.start()
        self.addCleanup(guard.stop)
        course.lessons.reload()
        self.said = []
        guard = patch.object(course.lesson, 'say', self.said.append)
        guard.start()
        self.addCleanup(guard.stop)
        self.topped = []                                    # a finished lesson asks for a spare item; never let it reach a model
        guard = patch.object(course.generate, 'top_up', lambda language, lesson_id: self.topped.append((language, lesson_id)))
        guard.start()
        self.addCleanup(guard.stop)
        self.warmed = []                                    # recordings are prepared in the background; never synthesize in tests
        guard = patch.object(course.lesson, 'warm', lambda language, recordings: self.warmed.append((language, recordings)))
        guard.start()
        self.addCleanup(guard.stop)
        self.emitted = []
        guard = patch('app.services.hooks.emit_soon', lambda event, persona=None, payload=None, **kw: self.emitted.append((event, payload)))
        guard.start()
        self.addCleanup(guard.stop)
        with closing(db.get_conn()) as conn, conn:
            conn.executescript((ROOT / 'backend/db/schema.sql').read_text('utf-8'))
            course.save_language_settings(conn, 'en', course.Teaching(mode='ambient', preset=COURSE))
        app = FastAPI()
        app.include_router(routes.router, prefix='/api')
        self.client = TestClient(app)
        self.addCleanup(self.client.close)

    def model(self, *answers):
        fake = Model(*answers)
        guard = patch('app.providers.registry.get_utility_provider', return_value=fake)
        guard.start()
        self.addCleanup(guard.stop)
        return fake

    def post(self, path, body=None, status=200):
        body = body or {}
        if path in ('answer', 'submit', 'quiz', 'stop'):
            body = {'run_id': getattr(self, 'run_id', None), **body}
        response = self.client.post('/api/teaching/lesson/' + path, json=body)
        self.assertEqual(response.status_code, status, response.text)
        result = response.json()
        if path == 'start' and status == 201:
            self.run_id = result['lesson']['id']
        return result

    def view(self):
        return self.client.get('/api/teaching/lesson').json()['lesson']

    def start(self, **body):
        return self.post('start', {'language': 'en', **body}, 201)['lesson']

    def to_write(self):
        lesson = self.start()
        return lesson

    def rows(self):
        with closing(db.get_conn()) as conn:
            return [dict(row) for row in conn.execute('SELECT * FROM course_events ORDER BY id')]

    def progress(self):
        return self.client.get('/api/teaching/settings/en').json()['progress']

    def finish(self, answer=None, text=ESSAY):
        self.to_write()
        self.model(answer or sheet())
        return self.post('submit', {'text': text, 'seconds': 300})['lesson']


